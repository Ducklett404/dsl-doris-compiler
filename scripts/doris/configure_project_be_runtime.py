"""Apply an owned, reversible BE runtime profile without widening resource budgets.

This tool does not register a formal snapshot or change any table or view. Only
the fixed private runtime-profile file is mutated, followed by an owned restart.
"""
import argparse
from datetime import datetime, timezone
import io
import json
from pathlib import Path
import re
import secrets
import tarfile
import time

import configure_project_be_memory as memory
from validate_project_sources import WslDoris

CONTAINER = memory.CONTAINER
CONF = memory.CONF
OVERRIDE = '/run/dsl-be-runtime-profile'
ENTRYPOINT_MARKER = 'DSL_BE_BOUNDED_RUNTIME_PROFILE_V1'
PROFILE = 'bounded-v1'
DISABLED = 'disabled-v1'
QUERY_MEMORY_BYTES = memory.QUERY_MEMORY_BYTES
CONTAINER_MEMORY_BYTES = 5368709120
CONTAINER_NANO_CPUS = 4000000000
RUNTIME_TARGET = {
    'num_cores': '4',
    'pipeline_executor_size': '4',
    'blocking_pipeline_executor_size': '8',
    'doris_scanner_thread_pool_thread_num': '8',
    'min_active_scan_threads': '8',
    'storage_page_cache_limit': '268435456',
    'pk_storage_page_cache_limit': '33554432',
    'je_dirty_decay_ms': '1000',
}
JEMALLOC_TARGET = ('percpu_arena:disabled,narenas:8,background_thread:true,'
    'max_background_threads:4,metadata_thp:auto,muzzy_decay_ms:1000,'
    'dirty_decay_ms:1000,oversize_threshold:0,prof:true,prof_active:false,'
    'lg_prof_interval:-1,lg_extent_max_active_fit:8,lg_tcache_max:15')
SOURCE_COUNTS = {'basic': '13650347', 'ext': '6170822', 'code': '5686'}
SOURCE_DATES = sorted([
    ('basic', '2006-01-04', '2026-04-14'),
    ('extension', '2018-08-20', '2026-04-14'),
])


def parse_override(text):
    if text == 'ABSENT\n':
        return None
    if not text.startswith('PRESENT\n'):
        raise ValueError('Unrecognized BE runtime-profile backup response')
    value = text[len('PRESENT\n'):]
    if not re.fullmatch(r'(bounded-v1|disabled-v1)(?:\r?\n)?', value):
        raise ValueError('BE runtime profile must be one line containing bounded-v1 or disabled-v1')
    return value


def override_archive(data):
    """Fixed single regular member; binary stdin also works for stopped Docker."""
    # Validate before creating recovery instructions, including exact line shape.
    parse_override('PRESENT\n' + data.decode('ascii'))
    output = io.BytesIO()
    with tarfile.open(fileobj=output, mode='w') as archive:
        member = tarfile.TarInfo(OVERRIDE.rsplit('/', 1)[1])
        member.size = len(data)
        member.mode = 0o600
        archive.addfile(member, io.BytesIO(data))
    return output.getvalue()


def parse_jemalloc(value):
    values = {}
    for item in value.split(','):
        key, separator, argument = item.partition(':')
        if not separator or not key or not argument or key in values:
            raise ValueError('Malformed or duplicate configured JEMALLOC option')
        values[key] = argument
    expected = dict(item.split(':', 1) for item in JEMALLOC_TARGET.split(','))
    if 'prof_prefix' in values:
        if not re.fullmatch(r'/opt/apache-doris/be/log/[A-Za-z0-9_.-]+', values.pop('prof_prefix')):
            raise ValueError('Unreviewed JEMALLOC profile output path')
    if values != expected:
        raise ValueError('Configured JEMALLOC options do not match the reviewed runtime profile')
    return values


def configuration_blocks(text):
    marker = '# --- BE_CONFIG_EXTRA ---\n'
    generated = '# --- generated by entrypoint.sh at container start ---\n'
    if text.count(marker) != 1 or text.count(generated) != 1:
        raise ValueError('Expected the reviewed generated BE_CONFIG_EXTRA configuration block')
    return text.split(marker)


def configured_jemalloc(text, before_text):
    # The image retains shipped defaults in be.conf.orig and reconstructs the
    # generated block on restart. Only the managed EXTRA must contain one JE
    # assignment; earlier factory assignments must be the exact prior bytes.
    prefix, extra = configuration_blocks(text)
    before_prefix, _ = configuration_blocks(before_text)
    assignment = r'^[ \t]*(?:export[ \t]+)?JEMALLOC_CONF[ \t]*=[^\r\n]*(?:\r?\n|$)'
    if re.findall(assignment, prefix, re.M) != re.findall(assignment, before_prefix, re.M):
        raise ValueError('Factory JEMALLOC assignments changed from their exact prior bytes')
    matches = re.findall(r'^[ \t]*(?:export[ \t]+)?JEMALLOC_CONF[ \t]*=[ \t]*(.*?)\r?$', extra, re.M)
    if len(matches) != 1:
        raise ValueError('Expected one managed JEMALLOC_CONF assignment at the end of the BE configuration')
    value = matches[0].strip()
    if len(value) >= 2 and value[0] in ('"', "'") and value[-1] == value[0]:
        value = value[1:-1]
    parse_jemalloc(value)
    return value


def validate_source_state(state):
    memory.validate_source_state(state)
    if state['tableCounts'] != sorted(SOURCE_COUNTS.items()):
        raise ValueError('Source row counts do not match the frozen three-file snapshot')
    if state['dateBounds'] != SOURCE_DATES:
        raise ValueError('Source date bounds do not match the frozen three-file snapshot')


class Application(memory.Application):
    def environment(self):
        environment = super().environment()
        if (environment['containerMemoryBytes'] != CONTAINER_MEMORY_BYTES
                or environment['containerNanoCpus'] != CONTAINER_NANO_CPUS
                or environment['feHeap'] != '768m' or environment['beHeap'] != '128m'):
            raise ValueError('Runtime profile requires the existing 5GiB/4CPU/FE768m/JNI128m diagnostic budgets')
        return environment

    def require_entrypoint(self):
        fingerprint = super().require_entrypoint()
        mounts = json.loads(self.run(['inspect', '-f', '{{json .Mounts}}', CONTAINER], timeout=20))
        tmpfs = json.loads(self.run(['inspect', '-f', '{{json .HostConfig.Tmpfs}}', CONTAINER], timeout=20)) or {}
        destinations = [m.get('Destination', '') for m in mounts if m.get('Destination') != memory.ENTRYPOINT] + list(tmpfs)
        if any(path and (OVERRIDE == path or OVERRIDE.startswith(path.rstrip('/') + '/')) for path in destinations):
            raise ValueError('Runtime-profile override must not be hidden by a mount or tmpfs')
        text = self.run(['exec', CONTAINER, 'cat', memory.ENTRYPOINT], timeout=20)
        if any(marker not in text for marker in (ENTRYPOINT_MARKER, OVERRIDE, PROFILE, DISABLED, 'JEMALLOC_CONF')):
            raise ValueError('Mounted diagnostic entrypoint lacks reviewed bounded runtime-profile support')
        return fingerprint

    def read_override(self):
        response = self.run(['exec', CONTAINER, 'sh', '-c',
            'if test -L "$1"; then exit 45; elif test -e "$1"; then '
            'test -f "$1" || exit 46; printf "PRESENT\\n"; cat -- "$1"; '
            'else printf "ABSENT\\n"; fi', 'dsl-be-runtime-read', OVERRIDE], timeout=20)
        return parse_override(response)

    def write_override_command(self, temporary):
        return ['exec', '-i', CONTAINER, 'sh', '-c',
            'test ! -L "$1" && { test ! -e "$1" || test -f "$1"; } && '
            'test ! -e "$2" && test ! -L "$2" && '
            'umask 077 && cat > "$2" && mv -- "$2" "$1"',
            'dsl-be-runtime-write', OVERRIDE, temporary]

    def selected_runtime(self, timeout=20):
        rows = json.loads(self.run(['exec', CONTAINER, 'curl', '-fsS', '--max-time', '10',
            f'http://127.0.0.1:{self.client.be_http_port}/api/show_config'], timeout=timeout))
        selected = {}
        for row in rows:
            if not isinstance(row, list) or len(row) < 3:
                raise ValueError('Unrecognized active BE configuration response')
            if row[0] in RUNTIME_TARGET:
                if row[0] in selected:
                    raise ValueError('Duplicate active BE configuration key')
                selected[row[0]] = str(row[2])
        if set(selected) != set(RUNTIME_TARGET):
            raise ValueError('Missing required active BE configuration key')
        return selected

    def workload_scan_limit(self):
        # Headers are needed here; don't depend on an undocumented column index.
        command = [argument for argument in self.client.command if argument != '--skip-column-names']
        output = self.execute(command, b'SHOW WORKLOAD GROUPS;\n', 20)
        rows = [line.split('\t') for line in output.splitlines() if line]
        if len(rows) < 2 or any(len(row) != len(rows[0]) for row in rows):
            raise ValueError('Unrecognized workload-group result')
        normalize = lambda value: re.sub('[^a-z0-9]', '', value.lower())
        headers = [normalize(value) for value in rows[0]]
        if headers.count('name') != 1 or headers.count('scanthreadnum') != 1:
            raise ValueError('Missing or ambiguous workload-group scan_thread_num column')
        name_index, scan_index = headers.index('name'), headers.index('scanthreadnum')
        normal = [row[scan_index] for row in rows[1:] if row[name_index] == 'normal']
        if len(normal) != 1 or not re.fullmatch(r'-?[0-9]+', normal[0]):
            raise ValueError('Missing or ambiguous normal workload group')
        value = int(normal[0])
        if value > 0:
            raise ValueError('Positive normal workload-group scan_thread_num would override the bounded profile')
        return value

    def wait_profile_ready(self, expected, attempts, sleeper):
        deadline = time.monotonic() + 180
        for attempt in range(attempts):
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                break
            try:
                if self.runtime(min(20, remaining)) == '60%' and self.selected_runtime(min(20, remaining)) == expected:
                    remaining = deadline - time.monotonic()
                    if remaining > 0 and self.query('SELECT 1', min(10, remaining)) == [('1',)]:
                        return
            except Exception:
                pass
            if attempt + 1 < attempts and time.monotonic() < deadline:
                sleeper(1)
        raise RuntimeError('Diagnostic BE/source readiness failed for the expected runtime profile')


def apply_configuration(client, folder, attempts=180, sleeper=time.sleep):
    folder = Path(folder).resolve()
    app = Application(client)
    report = dict(purpose='OWNED_DIAGNOSTIC_BE_RUNTIME_PROFILE', officialAcceptanceEligible=False,
        queryMaxExecutionMemoryBytes=QUERY_MEMORY_BYTES, queryTimeoutSeconds=10,
        overridePath=OVERRIDE, configurationPath=CONF, targetProfile=PROFILE,
        status='RUNNING', rollbackStatus='NOT_NEEDED', startedAtUtc=datetime.now(timezone.utc).isoformat())
    mutation_started = False
    before = environment = old_override = before_runtime = before_active = None
    rollback_tar = None
    pending = OVERRIDE + '.new-' + secrets.token_hex(8)
    try:
        app.ownership()
        report['containerId'] = app.container_id
        environment = app.environment()
        report['environmentBefore'] = environment
        report['entrypointSha256'] = app.require_entrypoint()
        if app.runtime() != '60%':
            raise ValueError('Expected the current active 60% BE memory share')
        old_override = app.read_override()
        if old_override is not None and old_override.rstrip('\r\n') != DISABLED:
            raise ValueError('Expected an absent or disabled-v1 runtime-profile override before first application')
        before_runtime = app.selected_runtime()
        before_active = app.run(['exec', CONTAINER, 'cat', CONF], timeout=20)
        configuration_blocks(before_active)
        (folder / 'be-conf-before.txt').write_bytes(before_active.encode('utf-8'))
        (folder / 'override-before.txt').write_bytes(b'ABSENT\n' if old_override is None else old_override.encode('utf-8'))
        rollback_bytes = (DISABLED + '\n').encode('ascii') if old_override is None else old_override.encode('ascii')
        (folder / 'override-rollback.txt').write_bytes(rollback_bytes)
        rollback_tar = override_archive(rollback_bytes)
        (folder / 'override-rollback.tar').write_bytes(rollback_tar)
        report.update(overrideBefore='ABSENT' if old_override is None else old_override,
            rollbackFileState='EXPLICIT_DISABLED_RESTORES_PREVIOUS_EFFECTIVE_PROFILE' if old_override is None else 'ORIGINAL_BYTES',
            activeConfigurationBeforeSha256=memory.sha(before_active), runtimeBefore=before_runtime,
            runtimeTarget=RUNTIME_TARGET, jemallocTarget=JEMALLOC_TARGET,
            beforeBeShare='60%', afterBeShare='60%', beforeBeBytes=3221225472, afterBeBytes=3221225472)
        before = app.state()
        validate_source_state(before)
        report['sourceStateBefore'] = before
        report['normalWorkloadScanThreadNumBefore'] = app.workload_scan_limit()
        app.ownership()
        restore_command = ['cp', '-', CONTAINER + ':/run']
        report['rollbackCommands'] = [client.prefix + restore_command, client.prefix + ['restart', CONTAINER]]
        report['rollbackStdinArtifact'] = 'override-rollback.tar'
        report['rollbackInstructions'] = ('Feed the recorded fixed single-member tar as binary stdin to the first rollback command, '
            'then restart only the same owned diagnostic container. No data volume is replaced.')
        (folder / 'result.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
        mutation_started = True
        app.run(app.write_override_command(pending), (PROFILE + '\n').encode('ascii'))
        if app.read_override() != PROFILE + '\n':
            raise ValueError('BE runtime-profile write did not match the requested value')
        app.restart()
        app.wait_profile_ready(RUNTIME_TARGET, attempts, sleeper)
        app.ownership()
        after = app.state()
        report['sourceStateAfter'] = after
        validate_source_state(after)
        if after != before:
            raise ValueError('Source counts, date bounds, semantic views or formal registry changed')
        if app.environment() != environment or app.require_entrypoint() != report['entrypointSha256']:
            raise ValueError('Container budgets, heaps or mounted entrypoint changed')
        active_after = app.run(['exec', CONTAINER, 'cat', CONF], timeout=20)
        (folder / 'be-conf-after.txt').write_bytes(active_after.encode('utf-8'))
        report['configuredJemallocAfter'] = configured_jemalloc(active_after, before_active)
        report['normalWorkloadScanThreadNumAfter'] = app.workload_scan_limit()
        runtime_after, share_after = app.selected_runtime(), app.runtime()
        if runtime_after != RUNTIME_TARGET or share_after != '60%':
            raise ValueError('Selected BE configuration changed after the readiness check')
        if report['normalWorkloadScanThreadNumAfter'] != report['normalWorkloadScanThreadNumBefore']:
            raise ValueError('Normal workload-group scan thread configuration changed during application')
        report.update(status='PASS', runtimeAfter=runtime_after, runtimeBeShare=share_after,
            allocatorVerification='CONFIGURED_ASSIGNMENT_ONLY_PROCESS_ENV_REQUIRES_SEPARATE_PROBE',
            sourceStateUnchanged=True, containerAndHeapBudgetsUnchanged=True,
            activeConfigurationAfterSha256=memory.sha(active_after))
    except Exception as error:
        report.update(status='FAIL', fatalError=str(error))
        if mutation_started:
            rollback_errors = []
            try:
                app.ownership()
                app.run(['cp', '-', CONTAINER + ':/run'], rollback_tar)
            except Exception as rollback_error:
                rollback_errors.append(str(rollback_error))
            try:
                app.restart()
                app.wait_profile_ready(before_runtime, attempts, sleeper)
                app.ownership()
                if app.read_override() != rollback_bytes.decode('ascii'):
                    raise ValueError('Rollback did not restore the exact override bytes')
                restored = app.state()
                validate_source_state(restored)
                if restored != before or app.environment() != environment or app.require_entrypoint() != report['entrypointSha256']:
                    raise ValueError('Rollback did not restore original source state, entrypoint and budgets')
                active_restored = app.run(['exec', CONTAINER, 'cat', CONF], timeout=20)
                (folder / 'be-conf-rollback.txt').write_bytes(active_restored.encode('utf-8'))
                if active_restored != before_active:
                    raise ValueError('Rollback did not restore the original active BE configuration')
                report['normalWorkloadScanThreadNumRollback'] = app.workload_scan_limit()
                if report['normalWorkloadScanThreadNumRollback'] != report['normalWorkloadScanThreadNumBefore']:
                    raise ValueError('Rollback did not restore the original normal workload-group scan thread configuration')
                report.update(rollbackRuntimeBeShare=app.runtime(), runtimeRollback=app.selected_runtime(),
                    sourceStateRollback=restored, activeConfigurationRollbackSha256=memory.sha(active_restored))
            except Exception as rollback_error:
                rollback_errors.append(str(rollback_error))
            report.update(rollbackStatus='FAILED' if rollback_errors else 'DONE', rollbackErrors=rollback_errors)
    finally:
        report['completedAtUtc'] = datetime.now(timezone.utc).isoformat()
        (folder / 'result.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--report-dir', '--output-dir', dest='report_dir', type=Path, required=True)
    parser.add_argument('--distribution', default='dsl-doris-official-01a104f9')
    parser.add_argument('--apply', action='store_true', help='Explicitly permit the owned profile write and retained-data restart')
    args = parser.parse_args()
    if not args.apply:
        parser.error('--apply is required; the tool will write the private override and restart the owned diagnostic container')
    folder = args.report_dir.resolve()
    if folder.exists():
        raise ValueError('Use a fresh report directory')
    folder.mkdir(parents=True)
    try:
        client = WslDoris(args.distribution, CONTAINER)
    except Exception as error:
        report = dict(status='FAIL', fatalError=str(error), rollbackStatus='NOT_NEEDED', officialAcceptanceEligible=False)
        (folder / 'result.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
        return 1
    report = apply_configuration(client, folder)
    print(json.dumps({key: report[key] for key in ('status', 'rollbackStatus', 'queryMaxExecutionMemoryBytes')}))
    return 0 if report['status'] == 'PASS' else 1


if __name__ == '__main__':
    raise SystemExit(main())
